#!/usr/bin/env node
/**
 * Bundle everything in public/ into a JavaScript module the Worker can serve.
 *
 * Workers have no filesystem at runtime, so a static file has to arrive inside
 * the bundle. This walks public/, base64 encodes each file, and writes
 * src/assets.js with the served path, content type and cache policy alongside.
 *
 * Run after changing anything in public/:
 *   npm run build:assets
 *
 * The output is committed, because the deploy has to work from a clean
 * checkout without anyone remembering to run this first.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const publicDir = join(here, '..', 'public');
const outFile = join(here, '..', 'src', 'assets.js');

const TYPES = {
  '.ico': 'image/x-icon',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.ttf': 'font/ttf',
  '.webmanifest': 'application/manifest+json',
  '.json': 'application/json',
};

// A year, immutable, for anything whose bytes are fixed. The manifest gets a
// day, because it is the one file likely to be edited without the icons
// changing, and a stale copy would misdescribe the install.
const IMMUTABLE = 'public, max-age=31536000, immutable';
const SHORT = 'public, max-age=86400';

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith('.')) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const files = walk(publicDir).sort();
if (!files.length) {
  console.error('public/ is empty, refusing to write an empty asset module');
  process.exit(1);
}

const entries = [];
let total = 0;

for (const file of files) {
  const rel = relative(publicDir, file).split(sep).join('/');
  const urlPath = '/' + rel;
  const ext = rel.slice(rel.lastIndexOf('.'));
  const type = TYPES[ext];
  if (!type) {
    console.error(`no content type mapped for ${rel}, add one to TYPES`);
    process.exit(1);
  }
  const bytes = readFileSync(file);
  total += bytes.length;
  entries.push({
    urlPath,
    type: ext === '.webmanifest' || ext === '.json' ? `${type}; charset=utf-8` : type,
    cache: ext === '.webmanifest' ? SHORT : IMMUTABLE,
    b64: bytes.toString('base64'),
  });
  console.log(`  ${urlPath.padEnd(34)} ${type.padEnd(26)} ${String(bytes.length).padStart(7)} bytes`);
}

const body = `/**
 * Generated by scripts/build-assets.mjs. Do not edit by hand.
 *
 * Static files from public/, inlined because a Worker has no filesystem at
 * runtime. Regenerate with: npm run build:assets
 */

/** @type {Record<string, {type: string, cache: string, b64: string}>} */
export const ASSETS = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.urlPath)}: {\n` +
      `    type: ${JSON.stringify(e.type)},\n` +
      `    cache: ${JSON.stringify(e.cache)},\n` +
      `    b64:\n      ${JSON.stringify(e.b64)},\n` +
      `  },`
  )
  .join('\n')}
};

const decoded = new Map();

/**
 * Serve one bundled asset, or null when the path is not one of ours.
 * @returns {Response|null}
 */
export function serveAsset(pathname) {
  const asset = ASSETS[pathname];
  if (!asset) return null;

  let bytes = decoded.get(pathname);
  if (!bytes) {
    const binary = atob(asset.b64);
    bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
    decoded.set(pathname, bytes);
  }

  return new Response(bytes, {
    headers: {
      'Content-Type': asset.type,
      'Cache-Control': asset.cache,
      'Content-Length': String(bytes.length),
    },
  });
}
`;

writeFileSync(outFile, body);
console.log(`\n${entries.length} assets, ${(total / 1024).toFixed(1)} KiB raw, written to src/assets.js`);
